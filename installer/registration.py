"""Register an isolated configuration and executable without editing shell files."""
import os
from pathlib import Path
import shlex
import tempfile

APP = 'uzume'
HEADER = '#!/bin/sh\n# Generated by Uzume setup-editor.\n'


def locations(bin_dir):
    config = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')).expanduser().absolute() / APP
    return config, bin_dir.expanduser().absolute() / 'uzume'


def preflight(source, bin_dir):
    config, launcher = locations(bin_dir)
    if os.path.lexists(config) and (not config.is_symlink() or config.resolve() != source.resolve()):
        raise RuntimeError('Refusing to replace existing configuration: ' + str(config))
    if os.path.lexists(launcher):
        if launcher.is_symlink() or not launcher.is_file() or not launcher.read_text().startswith(HEADER):
            raise RuntimeError('Refusing to replace an unrelated launcher: ' + str(launcher))
    return config, launcher


def register(source, bin_dir):
    config, launcher = preflight(source, bin_dir)
    lines = [HEADER.rstrip(), 'export NVIM_APPNAME=' + APP]
    for name, default in [('CONFIG', '.config'), ('DATA', '.local/share'), ('STATE', '.local/state'), ('CACHE', '.cache')]:
        key = 'XDG_' + name + '_HOME'
        value = Path(os.environ.get(key, Path.home() / default)).expanduser().absolute()
        lines.append('export ' + key + '=' + shlex.quote(str(value)))
    lines.append('exec nvim "$@"')
    launcher.parent.mkdir(parents=True, exist_ok=True)
    config.parent.mkdir(parents=True, exist_ok=True)
    if not config.is_symlink():
        config.symlink_to(source.resolve(), target_is_directory=True)
    fd, temporary = tempfile.mkstemp(prefix='.uzume-', dir=launcher.parent)
    try:
        with os.fdopen(fd, 'w') as output:
            output.write('\n'.join(lines) + '\n')
        os.chmod(temporary, 0o755)
        os.replace(temporary, launcher)
    finally:
        Path(temporary).unlink(missing_ok=True)
    print('Registered ' + str(config) + ' -> ' + str(source))
    print('Launch: ' + str(launcher))
    if str(launcher.parent) not in os.environ.get('PATH', '').split(os.pathsep):
        print('To use the short command, add this directory to PATH: ' + str(launcher.parent))
    print('Shell files and your default nvim configuration were not changed.')
